import { STEP_META, type AppState, type FormStepKey, type StepForm, type StepKey } from "./types";

function iso(date: string): string {
  return new Date(`${date}T09:00:00.000Z`).toISOString();
}

function formId(projectId: string, key: FormStepKey): string {
  return `form-${projectId}-${key}`;
}

function defaultPayload(key: FormStepKey) {
  if (key === "survey") {
    return {
      surveyDate: "",
      location: "",
      pic: "",
      findings: "",
      notes: "",
    };
  }
  if (key === "rab") {
    return { items: [], notes: "" };
  }
  if (key === "bast") {
    return { number: "", date: "", notes: "", documentUrl: "" };
  }
  return {
    number: "",
    date: "",
    amount: 0,
    taxPercent: 11,
    taxAmount: 0,
    notes: "",
    documentUrl: "",
  };
}

function makeForms(
  projectId: string,
  overrides: Partial<Record<FormStepKey, Partial<StepForm>>> = {},
): StepForm[] {
  const keys: FormStepKey[] = ["survey", "rab", "bast", "invoice"];
  return keys.map((key) => ({
    id: formId(projectId, key),
    projectId,
    stepKey: key,
    type: key,
    status: "unassigned",
    assigneeId: undefined,
    payload: defaultPayload(key),
    photos: key === "survey" ? [] : undefined,
    createdAt: iso("2026-10-01"),
    ...overrides[key],
  }));
}

function makeSteps(
  projectId: string,
  activeKeys: StepKey[],
  completedKeys: StepKey[] = [],
) {
  return STEP_META.map((meta) => ({
    id: `step-${projectId}-${meta.key}`,
    projectId,
    key: meta.key,
    phase: meta.phase,
    order: meta.order,
    status: completedKeys.includes(meta.key)
      ? ("completed" as const)
      : activeKeys.includes(meta.key)
        ? ("active" as const)
        : ("pending" as const),
    startedAt: completedKeys.includes(meta.key) || activeKeys.includes(meta.key)
      ? iso("2026-10-01")
      : undefined,
    completedAt: completedKeys.includes(meta.key)
      ? iso("2026-10-20")
      : undefined,
  }));
}

